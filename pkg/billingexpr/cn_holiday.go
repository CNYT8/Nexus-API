// IsCNHoliday reports whether the calendar date of t is a Chinese statutory
// holiday (中国法定节假日). For years outside the explicit table, fixed-date
// solar statutory holidays (New Year Jan 1, Qingming Apr 4-5, Labor Day May 1-5,
// National Day Oct 1-7) are still matched as a safe fallback.
func IsCNHoliday(t time.Time) bool {
	year, month, day := t.Date()
	key := fmt.Sprintf("%04d-%02d-%02d", year, int(month), day)
	if _, ok := cnStatutoryHolidays[key]; ok {
		return true
	}
	if year < 2024 || year > 2030 {
		switch month {
		case time.January:
			return day == 1
		case time.April:
			return day == 4 || day == 5
		case time.May:
			return day >= 1 && day <= 5
		case time.October:
			return day >= 1 && day <= 7
		}
	}
	return false
}

// IsCNOffday reports whether t falls on a weekend (Saturday or Sunday) or a
// Chinese statutory holiday (周末及中国法定节假日).
func IsCNOffday(t time.Time) bool {
	wd := t.Weekday()
	if wd == time.Saturday || wd == time.Sunday {
		return true
	}
	return IsCNHoliday(t)
}

// IsCNWorkday reports whether t is Monday through Friday and NOT a Chinese
// statutory holiday (周一至周五，不含中国法定节假日).
func IsCNWorkday(t time.Time) bool {
	return !IsCNOffday(t)
}

func cnHolidayInt(tz string) int {
	if IsCNHoliday(timeInZone(tz)) {
		return 1
	}
	return 0
}

func cnOffdayInt(tz string) int {
	if IsCNOffday(timeInZone(tz)) {
		return 1
	}
	return 0
}

func cnWorkdayInt(tz string) int {
	if IsCNWorkday(timeInZone(tz)) {
		return 1
	}
	return 0
}
