package model

import (
	"encoding/json"
	"errors"
	"time"
)

// TaskPlugin is an immutable, declarative billing revision for existing task
// adapters. Bind its ID via task_setting.usage_plugins; editing creates a new row.
// Network access and executable provider scripts are intentionally not supported.
type TaskPlugin struct {
	ID         int64  `json:"id" gorm:"primaryKey;autoIncrement"`
	Name       string `json:"name" gorm:"type:varchar(96);uniqueIndex:idx_nexus_task_plugin_revision"`
	Version    string `json:"version" gorm:"type:varchar(64);uniqueIndex:idx_nexus_task_plugin_revision"`
	Schema     string `json:"schema" gorm:"type:text"`
	Expression string `json:"expression" gorm:"type:text"`
	CreatedAt  int64  `json:"created_at"`
	// Local declarative counterpart of the upstream server-side route policy.
	// nil retains results; false discards only submit-time terminal results.
	RetainResult *bool `json:"retainResult,omitempty" gorm:"column:retain_result"`
}

// Paths are dotted object keys in the provider response (no arrays or wildcards).
// Expressions return USD before the frozen group and adapter multipliers.
type TaskUsageField struct {
	Path          string   `json:"path"`
	Required      bool     `json:"required"`
	Default       float64  `json:"default"`
	Max           float64  `json:"max"`
	Type          string   `json:"type,omitempty"`
	Enum          []string `json:"enum,omitempty"`
	DefaultString string   `json:"default_string,omitempty"`
	DefaultBool   bool     `json:"default_bool,omitempty"`
}

type TaskUsageSnapshot struct {
	PluginID     int64                     `json:"plugin_id"`
	Name         string                    `json:"name"`
	Version      string                    `json:"version"`
	Schema       map[string]TaskUsageField `json:"schema"`
	Expression   string                    `json:"expression"`
	GroupRatio   float64                   `json:"group_ratio"`
	OtherRatios  map[string]float64        `json:"other_ratios"`
	QuotaPerUnit float64                   `json:"quota_per_unit"`
	RetainResult *bool                     `json:"retain_result,omitempty"`
}

type TaskArtifact struct {
	ID         string `json:"id"`
	Kind       string `json:"kind"`
	URL        string `json:"url,omitempty"`
	MimeType   string `json:"mime_type,omitempty"`
	ContentURL string `json:"content_url,omitempty"` // Generated by the owner API, never trusted from provider input.
}

// TaskResultMetadata is private at rest. Controllers return only owner-scoped,
// validated artifacts and explicit text results, never raw provider metadata.
type TaskResultMetadata struct {
	Artifacts []TaskArtifact `json:"artifacts,omitempty"`
	Text      string         `json:"text,omitempty"`
}

func CreateTaskPlugin(plugin *TaskPlugin) error {
	if plugin == nil || plugin.ID != 0 || plugin.Name == "" || plugin.Version == "" || !json.Valid([]byte(plugin.Schema)) {
		return errors.New("invalid task plugin revision")
	}
	plugin.CreatedAt = time.Now().Unix()
	return DB.Create(plugin).Error
}

func GetTaskPlugin(id int64) (*TaskPlugin, error) {
	var plugin TaskPlugin
	if id <= 0 {
		return nil, errors.New("invalid task plugin id")
	}
	err := DB.First(&plugin, id).Error
	return &plugin, err
}

func ListTaskPlugins(beforeID int64, limit int) ([]TaskPlugin, error) {
	if limit <= 0 || limit > 100 {
		limit = 100
	}
	query := DB.Model(&TaskPlugin{})
	if beforeID > 0 {
		query = query.Where("id < ?", beforeID)
	}
	var plugins []TaskPlugin
	err := query.Order("id DESC").Limit(limit).Find(&plugins).Error
	return plugins, err
}
